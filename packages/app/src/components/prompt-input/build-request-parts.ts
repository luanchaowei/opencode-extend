import { type AgentPartInput, type FilePartInput, type Part, type TextPartInput } from "@opencode-ai/sdk/v2/client"
import type { FileSelection } from "@/context/file"
import type { Prompt } from "@/context/prompt"
import { Identifier } from "@/utils/id"

type PromptRequestPart = (TextPartInput | FilePartInput | AgentPartInput) & { id: string }

type ContextFile = {
  key: string
  type: "file"
  path: string
  selection?: FileSelection
  comment?: string
  commentID?: string
  commentOrigin?: "review" | "file"
  preview?: string
}

type BuildRequestPartsInput = {
  prompt: Prompt
  context: ContextFile[]
  text: string
  messageID: string
  sessionID: string
  sessionDirectory: string
}

const toOptimisticPart = (part: PromptRequestPart, sessionID: string, messageID: string): Part => {
  if (part.type === "text") {
    return {
      id: part.id,
      type: "text",
      text: part.text,
      synthetic: part.synthetic,
      ignored: part.ignored,
      time: part.time,
      metadata: part.metadata,
      sessionID,
      messageID,
    }
  }
  if (part.type === "file") {
    return {
      id: part.id,
      type: "file",
      mime: part.mime,
      filename: part.filename,
      url: part.url,
      source: part.source,
      sessionID,
      messageID,
    }
  }
  return {
    id: part.id,
    type: "agent",
    name: part.name,
    source: part.source,
    sessionID,
    messageID,
  }
}

export function buildRequestParts(input: BuildRequestPartsInput) {
  const sessionInfoPart: PromptRequestPart = {
    id: Identifier.ascending("part"),
    type: "text",
    text: `<system-reminder>
Current session ID: ${input.sessionID}
This information is provided for your context. You do not need to respond to or reference this ID unless the user specifically asks about it.
</system-reminder>`,
    synthetic: true,
  }

  const requestParts: PromptRequestPart[] = [
    sessionInfoPart,
    {
      id: Identifier.ascending("part"),
      type: "text",
      text: input.text,
    },
  ]

  return {
    requestParts,
    optimisticParts: requestParts.map((part) => toOptimisticPart(part, input.sessionID, input.messageID)),
  }
}
