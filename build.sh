#!/bin/bash

set -e

cd "$(dirname "$0")"

# === 解析目标平台参数 ===
# 用法: bash build.sh [--all] [--target=<平台>]
# 默认: --all (构建全部4个平台)
ALL_TARGETS=("linux-x64" "linux-arm64" "windows-x64" "windows-arm64")
TARGETS=()
for arg in "$@"; do
  case "$arg" in
    --all)          TARGETS=("${ALL_TARGETS[@]}");;
    --target=*)
      local_target="${arg#--target=}"
      valid=false
      for t in "${ALL_TARGETS[@]}"; do
        if [[ "$t" == "$local_target" ]]; then valid=true; break; fi
      done
      if [[ "$valid" == false ]]; then
        echo "错误: 未知平台 '$local_target'"
        echo "可选平台: ${ALL_TARGETS[*]}"
        exit 1
      fi
      TARGETS=("$local_target")
      ;;
    --help|-h)
      echo "用法: bash build.sh [--all] [--target=<平台>]"
      echo ""
      echo "选项:"
      echo "  --all              构建全部4个平台 (默认)"
      echo "  --target=<平台>    只构建指定平台"
      echo ""
      echo "可选平台:"
      echo "  linux-x64       Linux x86_64"
      echo "  linux-arm64     Linux ARM64"
      echo "  windows-x64     Windows x86_64"
      echo "  windows-arm64   Windows ARM64"
      echo ""
      echo "示例:"
      echo "  bash build.sh                          # 构建全部平台"
      echo "  bash build.sh --all                    # 构建全部平台"
      echo "  bash build.sh --target=linux-arm64     # 只构建 linux-arm64"
      exit 0
      ;;
    *)
      echo "未知参数: $arg"
      echo "运行 'bash build.sh --help' 查看用法"
      exit 1
      ;;
  esac
done

# 无参数时默认构建全部
if [[ ${#TARGETS[@]} -eq 0 ]]; then
  TARGETS=("${ALL_TARGETS[@]}")
fi

echo "=== 目标平台: ${TARGETS[*]} ==="
echo ""

echo "=== 1. 安装依赖 ==="
bun install

echo "=== 2. 构建前端 ==="
bun --cwd packages/app build

echo "=== 3. 生成内嵌资源清单 ==="
APP_DIR="packages/app"
DIST_DIR="$APP_DIR/dist"
MANIFEST_FILE="$APP_DIR/embedded-manifest.js"

bun -e "
import { readdirSync, readFileSync, statSync } from 'fs'
import { join, relative } from 'path'

const distDir = '$DIST_DIR'
const files = {}

function scan(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name)
    if (statSync(full).isDirectory()) {
      scan(full)
    } else {
      const rel = '/' + relative(distDir, full)
      const buf = readFileSync(full)
      files[rel] = { content: buf.toString('base64') }
    }
  }
}
scan(distDir)

const output = '// Auto-generated by build.sh - do not edit\nexport const embeddedFiles = ' + JSON.stringify(files) + '\n'
await Bun.write('$MANIFEST_FILE', output)
console.log('Generated manifest with', Object.keys(files).length, 'files')
"

OUTPUT_DIR="dist-bin"
mkdir -p "$OUTPUT_DIR"

# 生成 .env.example 模板 (只需一次)
cat > "$OUTPUT_DIR/.env.example" << 'ENV_EXAMPLE'
# === 服务配置 ===
WEB_HOST=0.0.0.0                          # 前端监听地址
WEB_PORT=3000                             # 前端端口
LOG_PATH=/tmp/opencode-extend.log         # 日志路径

# === 后端配置 ===
VITE_OPENCODE_SERVER_HOST=127.0.0.1       # opencode 后端地址
VITE_OPENCODE_SERVER_PORT=4096            # opencode 后端端口
VITE_OPENCODE_SERVER_PASSWORD=            # 后端认证密码，为空不认证
VITE_OPENCODE_SERVER_USERNAME=opencode    # 后端认证用户名

# === 用户目录 ===
VITE_OPENCODE_DEFAULT_DIR=/home/user/client  # 用户工作目录基准路径，每个IP/用户自动创建子目录

# === 登录认证 ===
AUTH_ENABLED=false                        # 是否启用登录，false=不登录直接用
ADMIN_USERNAME=admin                      # 超级管理员用户名（仅 AUTH_ENABLED=true 时生效）
ADMIN_PASSWORD=Admin123!                  # 超级管理员密码
VITE_REGISTRATION_ENABLED=false          # 是否开放用户自助注册，true=开放注册页面

# === 模型管理 ===
VITE_HIDDEN_PROVIDERS=                   # 隐藏的供应商 ID，逗号分隔
VITE_MODEL_TEST_TIMEOUT=30000            # 模型检测超时时间（毫秒），默认 30000
VITE_MODEL_TEST_DIR=/tmp/opencode-model-test  # 模型检测临时会话路径，使用干净目录避免 skill 干扰

# === 企业功能 ===
VITE_CONTACT_ADMIN=                       # 支撑人员，多个用 | 分隔
VITE_FEEDBACK_URL=                        # 问题反馈 URL
VITE_HELP_DOC_URL=                        # 帮助文档 URL
VITE_CASE_LIBRARY_DIR=                    # 知识库目录路径
VITE_ANNOUNCEMENT_TEXT=                   # 公告文案，为空不显示

# === 系统参数 ===
VITE_FILE_TREE_POLL_INTERVAL=10000        # 文件树刷新间隔（毫秒）
VITE_HEARTBEAT_INTERVAL=60000            # 心跳上报间隔（毫秒）
VITE_DISK_USAGE_THRESHOLD=90             # 磁盘使用率阈值（%），超过禁止上传

# === 统计数据 ===
VITE_STATS_DATA_PATH=/path/to/data        # stats.db 存储路径，默认可执行文件所在目录

# === 进程监控 ===
VITE_OPENCODE_SERVER_LOG=~/.local/share/opencode/log/opencode.log  # 后端日志路径，进程日志查看功能使用
VITE_MONITOR_DISK_MOUNTS=/               # 监控的磁盘挂载点，逗号分隔
VITE_MONITOR_BACKEND_PATTERN=            # 后端进程匹配规则，为空默认 opencode serve.*--port 端口
VITE_MONITOR_FRONTEND_PATTERN=           # 前端进程匹配规则，为空默认 bun.*packages/app
ENV_EXAMPLE

# === 4. 逐平台编译并打包 ===
INDEX=1
TOTAL=${#TARGETS[@]}
declare -a RESULTS

for target in "${TARGETS[@]}"; do
  bun_target="bun-${target}"
  case "$target" in
    windows-*) output_name="opencode-extend.exe";;
    *)         output_name="opencode-extend";;
  esac

  echo ""
  echo "=== [$INDEX/$TOTAL] 编译 $target ($bun_target) ==="

  bun build --compile --minify \
    --target "$bun_target" \
    --outfile "$OUTPUT_DIR/$output_name" \
    "$APP_DIR/server.js"

  tar czf "$OUTPUT_DIR/opencode-extend-$target.tar.gz" \
    -C "$OUTPUT_DIR" \
    "$output_name" \
    .env.example

  bin_size=$(du -h "$OUTPUT_DIR/$output_name" | cut -f1)
  tar_size=$(du -h "$OUTPUT_DIR/opencode-extend-$target.tar.gz" | cut -f1)
  RESULTS+=("$target|$output_name|$bin_size|$tar_size")

  INDEX=$((INDEX + 1))
done

# === 5. 清理临时文件 ===
rm -f "$MANIFEST_FILE"

# === 6. 汇总 ===
echo ""
echo "=== 编译完成 ==="
echo "目标平台: ${TARGETS[*]}"
echo ""
echo "平台             | 可执行文件              | 大小   | 安装包                                     | 大小"
echo "---------------- | ----------------------- | ------ | ------------------------------------------ | ------"
for result in "${RESULTS[@]}"; do
  IFS='|' read -r target output_name bin_size tar_size <<< "$result"
  printf "%-16s | %-23s | %-6s | %-42s | %s\n" "$target" "$output_name" "$bin_size" "opencode-extend-$target.tar.gz" "$tar_size"
done
echo ""
echo "输出目录: $OUTPUT_DIR/"
echo ""
echo "部署方式:"
echo "  1. 解压: tar xzf opencode-extend-<平台>.tar.gz"
echo "  2. 配置: cp .env.example .env && vim .env"
echo "  3. 启动: ./opencode-extend"
